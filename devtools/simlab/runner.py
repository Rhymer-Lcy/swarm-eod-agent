#!/usr/bin/env python3
"""Run one simulation round through the official launcher and record it.

The round is executed by ``swarm_rescue.launcher.Launcher.one_round`` with the
official map classes, score managers and competition-mode guard; this module
adds no simulation or scoring logic of its own. What it adds:

* an evaluation plan written per run (one map, one mode, one round);
* seeding of Python's ``random`` and NumPy's global generator before the map
  is built (the framework seeds neither; see the determinism probe for what
  the seed does and does not control);
* the agent under test, selected by ``--agent``: ``official`` uses the
  submission entry point ``solutions/my_drone_eval.drone_class_for_mode``
  exactly as the launcher does; ``module:Class`` names a development class
  (baselines, probes). The selection is made by replacing the launcher
  module's reference to ``drone_class_for_mode`` before the round, i.e. the
  same function the entry point provides; simulator, scoring and launcher
  logic are untouched;
* an optional ground-truth log (``diagnostics.with_truth_log``), which only
  reads state and never feeds anything back to the agent;
* a ledger: one JSON line is appended when a round starts and another when it
  ends, so a killed or crashed run stays visible as ``started`` without a
  matching ``finished`` line;
* a round budget: the run is refused when the ledger already holds
  ``--budget`` started rounds for ``--phase``;
* Phase 4 custom geometry: a ``--map`` value that is not ``Map01``-``Map05``
  names a scenario of ``p4_scenarios.py``, whose map class (framework
  elements only) is made resolvable by the launcher for this round. Such
  rounds are recorded with ``map_kind: custom`` and the specification's
  SHA-256; they are never official-map or competition results.

Run on a host with an OpenGL context (see docs/ENVIRONMENT.md), from the
repository root, for example::

    PYGLET_HEADLESS=True PYGLET_HEADLESS_DEVICE=7 python -m devtools.simlab.runner \
        --label p1-probe --map Map01 --mode place --drones 10 --bombs-per-drone 1 \
        --agent devtools.simlab.probe:DynamicsProbe --no-competition --seed 11
"""

from __future__ import annotations

import argparse
import contextlib
import datetime as _dt
import hashlib
import importlib
import io
import json
import os
import platform
import random
import subprocess
import sys
import time
import traceback
from pathlib import Path
from typing import Any, Dict, Optional

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_RUNS = REPO_ROOT / "_local" / "runs"
UTC8 = _dt.timezone(_dt.timedelta(hours=8))


def _now() -> str:
    return _dt.datetime.now(UTC8).isoformat(timespec="seconds")


def _git(*args: str) -> str:
    try:
        return subprocess.run(["git", "-C", str(REPO_ROOT), *args],
                              check=True, capture_output=True,
                              text=True).stdout.strip()
    except Exception as exc:  # pragma: no cover - recorded, not fatal
        return f"unavailable: {exc!r}"


def _sha256(path: Path) -> Optional[str]:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def ledger_rounds(ledger: Path, phase: str) -> int:
    """Number of rounds started under ``phase`` (finished or not)."""
    if not ledger.exists():
        return 0
    count = 0
    with ledger.open(encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if entry.get("event") == "started" and entry.get("phase") == phase:
                count += 1
    return count


def _append(ledger: Path, entry: Dict[str, Any]) -> None:
    ledger.parent.mkdir(parents=True, exist_ok=True)
    with ledger.open("a", encoding="utf-8") as f:
        f.write(json.dumps(entry, sort_keys=True) + "\n")


def write_plan(path: Path, *, map_name: str, mode: str, drones: int,
               bombs_per_drone: Optional[int], bombs_file: Optional[str]) -> None:
    """Write a one-round evaluation plan in the official YAML schema."""
    lines = [
        "# Generated by devtools/simlab/runner.py for a single local round.",
        "stat_saving_enabled: false",
        "state_recording_enabled: false",
        "video_capture_enabled: false",
        "",
        "evaluation_plan:",
        f"  - map_name: {map_name}",
        f"    team_mode: {mode}",
        "    nb_rounds: 1",
        "    config_weight: 1",
        f"    number_drones: {int(drones)}",
    ]
    if bombs_per_drone is not None:
        lines.append(f"    initial_bombs_per_drone: {int(bombs_per_drone)}")
    if bombs_file:
        lines.append(f"    bombs_file: {bombs_file}")
    lines.append("    zones_config: []")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def resolve_agent(spec: str):
    """Return ``(selector, description, module)`` for an ``--agent`` value.

    The selector has the signature of ``drone_class_for_mode``.
    """
    if spec == "official":
        from swarm_rescue.solutions import my_drone_eval
        return my_drone_eval.drone_class_for_mode, "official entry point", my_drone_eval
    module_name, _, class_name = spec.partition(":")
    if not class_name:
        raise SystemExit(f"--agent must be 'official' or 'module:Class', got {spec!r}")
    module = importlib.import_module(module_name)
    cls = getattr(module, class_name)
    return (lambda _mode: cls), spec, module


OFFICIAL_MAPS = tuple(f"Map0{i}" for i in range(1, 6))


def is_official_map(name: str) -> bool:
    return name in OFFICIAL_MAPS


def run_mode(args: argparse.Namespace) -> str:
    """How the agent was attached to the launcher in this round.

    ``native``: the official entry point exactly as the launcher imports it,
    competition mode on, no wrapper and no selector replacement.
    ``instrumented``: the agent class wrapped by the evaluation-only truth
    logger. ``harness``: no truth log, but the class was selected by the
    harness (comparators, probes, or the official class without --native).
    """
    if args.native:
        return "native"
    return "harness" if args.no_truth_log else "instrumented"


def classify_termination(mode: str, result: tuple, max_steps: int) -> str:
    (_, _, elapsed_timestep, _, _, disposed, _, _, walltime_hit, crashed,
     _, n_bombs, _, _, _) = result
    if crashed:
        return "crash"
    if walltime_hit:
        return "walltime_limit"
    if mode == "rescue":
        if n_bombs and int(disposed) >= int(n_bombs):
            return "all_disposed"
        return "step_limit" if elapsed_timestep >= max_steps else "other"
    return "step_limit" if elapsed_timestep >= max_steps else "map_submitted"


def run_round(args: argparse.Namespace) -> int:
    runs_root = Path(args.runs_root).resolve()
    ledger = runs_root / "ledger.jsonl"
    used = ledger_rounds(ledger, args.phase)
    if used >= args.budget:
        print(f"REFUSED: phase {args.phase!r} already has {used} rounds "
              f"(budget {args.budget}).", file=sys.stderr)
        return 3

    stamp = _dt.datetime.now(_dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    run_id = f"{stamp}_{args.label}"
    run_dir = runs_root / run_id
    run_dir.mkdir(parents=True, exist_ok=False)
    os.environ["SWARM_RESCUE_RESULTS_DIR"] = str(run_dir / "results")

    plan = run_dir / "plan.yml"
    bombs_file = str(Path(args.bombs_file).resolve()) if args.bombs_file else None
    write_plan(plan, map_name=args.map, mode=args.mode, drones=args.drones,
               bombs_per_drone=args.bombs_per_drone, bombs_file=bombs_file)

    custom = not is_official_map(args.map)
    custom_spec = None
    if custom:
        from . import p4_scenarios
        custom_spec = p4_scenarios.spec_by_name(args.map)
        map_source = Path(p4_scenarios.__file__)
    else:
        map_source = REPO_ROOT / "src" / "swarm_rescue" / "maps" / f"map_{args.map[-2:]}.py"
    base = {
        "run_id": run_id, "phase": args.phase, "label": args.label,
        "map": args.map, "mode": args.mode, "drones": args.drones,
        "bombs_per_drone": args.bombs_per_drone,
        "bombs_file": bombs_file,
        "bombs_file_sha256": _sha256(Path(bombs_file)) if bombs_file else None,
        "map_source_sha256": _sha256(map_source),
        "map_kind": "custom" if custom else "official",
        "custom_spec_sha256": p4_scenarios.spec_sha256(custom_spec) if custom else None,
        "custom_partition": custom_spec["partition"] if custom else None,
        "agent": args.agent, "competition_mode": not args.no_competition,
        "seed": args.seed, "truth_log": not args.no_truth_log,
        "run_mode": run_mode(args),
        "git_head": _git("rev-parse", "HEAD"),
        "git_dirty": bool(_git("status", "--porcelain")),
        "baseline_tag": _git("rev-parse", "baseline-supplied-5.1.3^{commit}"),
        "python": platform.python_version(), "platform": platform.platform(),
        "host_note": args.host_note,
        "env": {k: os.environ.get(k) for k in (
            "PYGLET_HEADLESS", "PYGLET_HEADLESS_DEVICE", "OMP_NUM_THREADS")},
    }
    _append(ledger, {**base, "event": "started", "time": _now(),
                     "round_index_in_phase": used + 1})

    random.seed(args.seed)
    import numpy as np
    np.random.seed(args.seed)

    import swarm_rescue.launcher as launcher_module
    from .diagnostics import TruthSink, with_truth_log

    if custom:
        # Evaluation-only map class made of framework elements; the launcher
        # resolves map names in its own namespace (devtools/simlab/p4_scenarios.py).
        p4_scenarios.register(launcher_module, args.map)

    selector, agent_desc, agent_module = resolve_agent(args.agent)
    sink = None if args.no_truth_log else TruthSink()
    if args.native:
        # The launcher's own reference to the entry point is used untouched.
        from swarm_rescue.solutions import my_drone_eval
        if launcher_module.drone_class_for_mode is not my_drone_eval.drone_class_for_mode:
            raise SystemExit("native mode: the launcher does not reference the entry point")
    else:
        if sink is not None:
            inner = selector
            cache: Dict[str, type] = {}

            def selector(mode: str):  # noqa: F811 - deliberate wrapping
                if mode not in cache:
                    cache[mode] = with_truth_log(inner(mode), sink)
                return cache[mode]
        launcher_module.drone_class_for_mode = selector

    stdout_path = run_dir / "stdout.log"
    started = time.perf_counter()
    status, error, result = "finished", None, None
    launcher = None
    with stdout_path.open("w", encoding="utf-8") as log, \
            contextlib.redirect_stdout(_Tee(sys.stdout, log)):
        try:
            launcher = launcher_module.Launcher(config_path=str(plan),
                                                team_mode=args.mode)
            eval_config = launcher.eval_plan.list_eval_config[0]
            result = launcher.one_round(eval_config, 1, False, True,
                                        not args.no_competition)
        except Exception:
            status, error = "harness_error", traceback.format_exc()
            print(error)
    wall = time.perf_counter() - started

    record: Dict[str, Any] = {**base, "event": "finished", "time": _now(),
                              "status": status, "agent_selector": agent_desc,
                              "harness_wall_s": round(wall, 2)}
    if error:
        record["error"] = error[-4000:]
    if result is not None and launcher is not None:
        record.update(_scores(args.mode, launcher, result))
        record["termination"] = classify_termination(
            args.mode, result, launcher.max_timestep_limit)
    if sink is not None:
        try:
            record["diagnostics"] = sink.save(run_dir)
            record["diagnostics"]["submitted_step_from_log"] = sink.submitted_step
        except Exception:
            record["diagnostics_error"] = traceback.format_exc()[-2000:]
    probe_save = getattr(agent_module, "save_probe_log", None)
    if callable(probe_save):
        probe_save(run_dir)
    (run_dir / "record.json").write_text(
        json.dumps(record, indent=1, sort_keys=True, default=str) + "\n",
        encoding="utf-8")
    _append(ledger, {k: record[k] for k in record if k != "diagnostics"})
    print(json.dumps({k: record.get(k) for k in (
        "run_id", "status", "termination", "elapsed_timestep",
        "round_score", "score_components")}, default=str))
    return 0 if status == "finished" and not record.get("crashed") else 1


def _scores(mode: str, launcher: Any, result: tuple) -> Dict[str, Any]:
    (percent_destroyed, mean_health, elapsed_timestep, full_disposal_timestep,
     score_exploration, disposed, score_health_returned, elapsed_walltime,
     walltime_hit, crashed, _team_mode, n_bombs, placed_path, remaining_inv,
     place_phase1) = result
    out: Dict[str, Any] = {
        "elapsed_timestep": int(elapsed_timestep),
        "max_timestep_limit": int(launcher.max_timestep_limit),
        "elapsed_walltime_s": round(float(elapsed_walltime), 2),
        "max_walltime_limit_s": launcher.max_walltime_limit,
        "walltime_limit_reached": bool(walltime_hit),
        "crashed": bool(crashed),
        "percent_drones_destroyed": float(percent_destroyed),
        "mean_drone_health": float(mean_health),
        "steps_per_second": round(float(elapsed_timestep) / max(float(elapsed_walltime), 1e-6), 1),
    }
    if mode == "rescue":
        round_score, percent_disposed, score_time = \
            launcher.score_manager.compute_score(
                disposed, score_exploration, score_health_returned,
                elapsed_timestep, crashed)
        out.update({
            "round_score": float(round_score),
            "score_components": {
                "disposal": float(percent_disposed),
                "health": float(score_health_returned),
                "time": float(score_time),
            },
            "bombs_total": int(n_bombs),
            "bombs_disposed": int(disposed),
            "full_disposal_timestep": int(full_disposal_timestep),
        })
    else:
        p1 = place_phase1
        out.update({
            "round_score": float(p1.round_score) if p1 else 0.0,
            "round_score_note": "partial: the bomb-difficulty term (20%) is "
                                "pending locally and counted as 0",
            "score_components": {
                "map": float(p1.score_map) if p1 else 0.0,
                "wall": float(p1.score_wall) if p1 else 0.0,
                "time": float(p1.score_time) if p1 else 0.0,
                "bomb": None,
            },
            "map_breakdown": p1.map_breakdown if p1 else None,
            "wall_breakdown": p1.wall_breakdown if p1 else None,
            "bombs_placed": int(n_bombs),
            "inventory_remaining": int(remaining_inv),
            "placed_bombs_file": placed_path,
            "placement_completion": (p1.bomb_breakdown or {}).get(
                "placement_completion") if p1 else None,
        })
    return out


class _Tee(io.TextIOBase):
    def __init__(self, *streams):
        self._streams = streams

    def write(self, s):  # type: ignore[override]
        for stream in self._streams:
            stream.write(s)
        return len(s)

    def flush(self):  # type: ignore[override]
        for stream in self._streams:
            stream.flush()


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--label", required=True, help="short run label (no spaces)")
    p.add_argument("--phase", default="phase4", help="budget bucket")
    p.add_argument("--budget", type=int, default=24,
                   help="maximum rounds started in this phase (default 24, the "
                        "Phase 4 authorization)")
    p.add_argument("--map", required=True,
                   help="official map (Map01-Map05) or a Phase 4 custom-geometry "
                        "scenario name (devtools/simlab/p4_scenarios.py, e.g. P4PocketV1)")
    p.add_argument("--mode", required=True, choices=["rescue", "place"])
    p.add_argument("--drones", type=int, default=10)
    p.add_argument("--bombs-per-drone", type=int, default=None)
    p.add_argument("--bombs-file", default=None)
    p.add_argument("--agent", default="official")
    p.add_argument("--seed", type=int, required=True)
    p.add_argument("--no-competition", action="store_true",
                   help="run without the ground-truth guard (probes only)")
    p.add_argument("--no-truth-log", action="store_true")
    p.add_argument("--native", action="store_true",
                   help="native competition-mode round: official entry point, "
                        "no truth log, no wrapper, no selector replacement")
    p.add_argument("--runs-root", default=str(DEFAULT_RUNS))
    p.add_argument("--host-note", default="", help="free text for the ledger")
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    if not is_official_map(args.map):
        from . import p4_scenarios
        try:
            p4_scenarios.parse_name(args.map)
        except KeyError as exc:
            print(f"--map: {exc}", file=sys.stderr)
            return 2
    if args.native:
        if args.agent != "official" or args.no_competition:
            print("--native requires --agent official and competition mode", file=sys.stderr)
            return 2
        args.no_truth_log = True
    if args.mode == "place" and args.bombs_per_drone is None:
        args.bombs_per_drone = 2
    if args.mode == "rescue" and not args.bombs_file:
        print("rescue rounds need --bombs-file", file=sys.stderr)
        return 2
    return run_round(args)


if __name__ == "__main__":
    sys.exit(main())
